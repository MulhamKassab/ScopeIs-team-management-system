import { expect, test } from "@playwright/test";
import { signIn, signOut } from "./sign-in";

test.skip(process.env.SCOPEIS_PHASE7_E2E !== "true", "Run with the guarded Phase 7 fixture runner.");

test("Cover combines timetable requests, editing, cancellation and direct decisions with role-safe planning", async ({ page }, info) => {
  test.setTimeout(180_000);
  const month = info.project.name === "mobile" ? "2045-10" : "2045-09";
  await signIn(page, "Ava Mercer");
  await page.goto(`/schedule?month=${month}&mode=planning`);
  await expect(page.getByRole("link", { name: "Planning · unpublished", exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Create assignment", exact: true })).toHaveCount(0);
  await page.goto(`/coverage?month=${month}`);
  await expect(page.getByRole("heading", { name: "Cover", exact: true })).toBeVisible();
  await page.getByRole("button", { name: /Open .*12 .*1 assignment/ }).click();
  const day = page.getByRole("dialog");
  await expect(day.getByText("Cora Bell", { exact: true })).toBeVisible();
  await day.getByRole("link", { name: "Request cover", exact: true }).click();
  await expect(day).not.toBeVisible();
  const create = page.locator("#selected-work").getByRole("form", { name: "Request coverage support" });
  await create.getByRole("combobox", { name: "Proposed person (optional)", exact: true }).selectOption({ label: "Eli Alpha" });
  await create.getByRole("button", { name: "Send cover request", exact: true }).click();
  await expect(create.getByRole("status")).toHaveText(/Cover request created/);
  const queue = page.locator("#current-requests");
  await expect(queue.locator("article")).toHaveCount(1);
  await expect(page.locator(".timetable-day.cover-pending")).toHaveCount(1);
  await expect(queue.getByRole("button", { name: "Approve cover", exact: true })).toHaveCount(0);
  await queue.getByRole("button", { name: "Edit request", exact: true }).click();
  const edit = page.getByRole("dialog", { name: "Edit cover request", exact: true });
  await edit.getByRole("combobox", { name: "Proposed person", exact: true }).selectOption("");
  await edit.getByRole("button", { name: "Save request", exact: true }).click();
  await expect(edit.getByRole("status")).toHaveText("Cover request updated.");
  await edit.getByRole("button", { name: "Close", exact: true }).click();
  const cancelledCardId = await queue.locator("article").getAttribute("id");
  await queue.getByRole("button", { name: "Cancel request", exact: true }).click();
  const cancel = page.getByRole("dialog", { name: "Cancel cover request", exact: true });
  await cancel.getByRole("button", { name: "Cancel request", exact: true }).click();
  await expect(queue.locator("article")).toHaveCount(0);
  // Cancellation removes the owning request card and restores focus to the section.
  await expect(page.getByRole("dialog", { name: "Cancel cover request" })).not.toBeVisible();
  await page.locator(".cover-history > summary").click();
  await expect(page.locator(`.cover-history #${cancelledCardId}`).getByText("Cancelled", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Create request", exact: true }).first().click();
  let composer = page.getByRole("dialog", { name: "Create cover request", exact: true });
  await composer.getByRole("button", { name: "Send cover request", exact: true }).click();
  await expect(composer.getByRole("status")).toHaveText(/Cover request created/);
  await composer.getByRole("button", { name: "Close", exact: true }).click();
  await page.evaluate(async () => { await Promise.all(document.getAnimations().filter((animation) => animation.effect?.getTiming().iterations !== Infinity).map((animation) => animation.finished.catch(() => undefined))); });
  await page.screenshot({ path: info.outputPath("cover-admin-pending.png"), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await signOut(page); await signIn(page, "Nora Albright");
  await page.goto(`/coverage?month=${month}`);
  await expect(queue.locator("article")).toHaveCount(1);
  await queue.getByRole("button", { name: "Reject request", exact: true }).click();
  await expect(queue.locator("article")).toHaveCount(0);
  await expect(page.locator(".workflow-feedback")).toHaveText("Replacement request decision saved.");
  await page.getByRole("button", { name: "Create request", exact: true }).first().click();
  composer = page.getByRole("dialog", { name: "Create cover request", exact: true });
  await composer.getByRole("button", { name: "Create cover request", exact: true }).click();
  await expect(composer.getByRole("status")).toHaveText(/Cover request created/);
  await composer.getByRole("button", { name: "Close", exact: true }).click();
  await queue.getByRole("combobox", { name: "Covering person", exact: true }).selectOption({ label: "Eli Alpha" });
  const approvedCardId = await queue.locator("article").getAttribute("id");
  await queue.getByRole("button", { name: "Approve cover", exact: true }).click();
  await expect(queue.locator("article")).toHaveCount(0);
  await expect(page.locator(".timetable-day.cover-approved")).toHaveCount(1);
  await page.screenshot({ path: info.outputPath("cover-super-admin-approved.png"), fullPage: true });
  await page.goto(`/schedule?month=${month}&date=${month}-13`);
  await page.getByRole("button", { name: "Create assignment", exact: true }).click();
  const assignmentDialog = page.getByRole("dialog", { name: "Create assignment", exact: true });
  await assignmentDialog.getByRole("combobox", { name: "Client schedule", exact: true }).selectOption({ label: `Gamma Operations · Draft ${month}` });
  const assignment = assignmentDialog.getByRole("form", { name: "Add schedule assignment" });
  await expect(assignment.getByLabel("Date", { exact: true })).toHaveValue(`${month}-13`);
  await assignment.getByRole("combobox", { name: "Employee", exact: true }).selectOption({ label: "Cora Bell" });
  await assignment.getByRole("combobox", { name: "Project", exact: true }).selectOption({ label: "Gamma Hidden Project" });
  await assignment.getByRole("combobox", { name: "Linked Location", exact: true }).selectOption({ label: "Gamma Scoped Location" });
  await assignment.getByRole("button", { name: "Add assignment", exact: true }).click();
  await expect(assignment.getByText("Assignment added to the Draft.")).toBeVisible();
  await assignmentDialog.getByRole("button", { name: "Close", exact: true }).click();
  await page.goto(`/map?date=${month}-12`);
  await expect(page.getByRole("button", { name: "Place labels", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(page.locator(".map-selection-card")).toContainText("Cora Bell");
  await page.screenshot({ path: info.outputPath("work-map-selection.png"), fullPage: true });
  await page.setViewportSize({ width: 320, height: 780 });
  await page.locator("html").evaluate((node) => { node.setAttribute("dir", "rtl"); node.setAttribute("data-theme", "dark"); });
  await page.screenshot({ path: info.outputPath("work-map-320-rtl-dark.png"), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await page.goto(`/coverage?month=${month}`);
  await page.locator(".cover-history > summary").click();
  await page.locator(`.cover-history #${approvedCardId}`).getByRole("link", { name: "Open Draft to publish", exact: true }).click();
  await page.getByRole("button", { name: "Propose for review", exact: true }).click();
  await page.getByRole("button", { name: "Publish schedule", exact: true }).click();
  await expect(page.locator(".workflow-lifecycle .schedule-status")).toHaveText("PUBLISHED");
  await page.goto(`/coverage?month=${month}`);
  await expect(page.locator(".timetable-day.cover-approved")).toHaveCount(0);
  await page.locator(".cover-history > summary").click();
  const publishedHistory = page.locator(`.cover-history #${approvedCardId}`);
  await expect(publishedHistory.getByText("Schedule published", { exact: true })).toBeVisible();
  await expect(publishedHistory.getByRole("link", { name: "Open Draft to publish", exact: true })).toHaveCount(0);
  await signOut(page); await signIn(page, "Cora Bell");
  await page.goto("/coverage");
  await expect(page.getByRole("heading", { name: "Cover is management-only", exact: true })).toBeVisible();
  await page.goto("/leave");
  await expect(page.getByRole("button", { name: "Apply for vacation", exact: true })).toBeVisible();
});

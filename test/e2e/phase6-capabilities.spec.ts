import { expect, test } from "@playwright/test";
import { signIn, signOut } from "./sign-in";

test.skip(process.env.SCOPEIS_PHASE6_E2E !== "true", "Run with the guarded Phase 6 fixture runner.");

test("Super Admin records a skill and the Employee sees only their own recorded fact", async ({ page }) => {
  const skillName = `Browser capability ${test.info().project.name}`;
  await signIn(page, "Nora Albright");
  await page.goto("/skills");
  await page.locator(".journey-disclosure > summary").filter({ hasText: "Manage skill list" }).click();
  await page.getByRole("button", { name: "Add skill" }).click();
  await page.getByRole("form", { name: "Create skill" }).getByLabel("Skill name").fill(skillName);
  await page.getByRole("form", { name: "Create skill" }).getByRole("button", { name: "Create skill" }).click();
  await expect(page.getByText("Skill created.")).toBeVisible();
  await page.getByRole("button", { name: "Close", exact: true }).click();
  await page.getByRole("combobox", { name: "Person", exact: true }).selectOption({ label: "Cora Bell" });
  await page.getByRole("button", { name: "View skills", exact: true }).click();
  await page.getByRole("button", { name: "Record a skill for Cora Bell", exact: true }).click();
  const record = page.getByRole("form", { name: "Record employee skill" });
  await expect(record.locator('input[name="employeeUserId"]')).toHaveValue("mock-employee-cora");
  await record.getByRole("combobox", { name: "Skill", exact: true }).selectOption({ label: skillName });
  await record.getByRole("button", { name: "Record skill" }).click();
  await expect(page.getByText("Recorded skill added to the Employee profile.")).toBeVisible();
  await page.getByRole("button", { name: "Close", exact: true }).click();
  await page.getByRole("form", { name: `Archive ${skillName}`, exact: true }).getByRole("button", { name: "Archive", exact: true }).click();
  await page.locator("summary").filter({ hasText: "Archived skills" }).click();
  await page.getByRole("form", { name: `Restore ${skillName}`, exact: true }).getByRole("button", { name: "Restore", exact: true }).click();
  await expect(page.getByText("Recorded skill restored; its history is retained.")).toBeVisible();
  await signOut(page);
  await signIn(page, "Cora Bell");
  await page.goto("/skills");
  await expect(page.getByRole("heading", { name: "My recorded skills" })).toBeVisible();
  await expect(page.getByText(skillName)).toBeVisible();
  await expect(page.getByText(/recorded by your Super Admin/i)).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
});

test("Super Admin manages missing controls while Admin and Employee remain excluded", async ({ page }) => {
  const suffix = test.info().project.name;
  await signIn(page, "Nora Albright");
  await page.goto("/arrangements");
  await page.getByRole("button", { name: "New label", exact: true }).click();
  const label = page.getByRole("form", { name: "Create assignment label" });
  await label.getByLabel("Name", { exact: true }).fill(`Site arrangement ${suffix}`);
  await label.getByLabel("Display order").fill("12");
  await label.getByRole("button", { name: "Save label" }).click();
  await expect(page.getByText("Label saved.")).toBeVisible();
  await page.getByRole("button", { name: "Close", exact: true }).click();
  await page.getByRole("button", { name: `Archive Site arrangement ${suffix}`, exact: true }).click();
  await page.getByRole("button", { name: "Archive label", exact: true }).click();
  await expect(page.getByText("Label archived; history retained.")).toBeVisible();
  await page.getByRole("button", { name: "Close", exact: true }).click();
  await page.getByRole("button", { name: `Reactivate Site arrangement ${suffix}`, exact: true }).click();
  await page.getByRole("button", { name: "Reactivate label", exact: true }).click();
  await expect(page.getByText("Label reactivated.")).toBeVisible();
  await page.getByRole("button", { name: "Close", exact: true }).click();
  await page.goto("/designations");
  await page.getByRole("button", { name: "New job title", exact: true }).click();
  await page.getByLabel("Job title name").fill(`Field title ${suffix}`);
  await page.getByRole("button", { name: "Create job title", exact: true }).click();
  await expect(page.locator(".workflow-feedback")).toContainText("Saved. This record is available in team and job title options.");
  const titleDialog = page.getByRole("dialog", { name: "Create job title", exact: true });
  if (await titleDialog.isVisible()) await titleDialog.getByRole("button", { name: "Close", exact: true }).click();
  const titleCard = page.getByRole("heading", { name: `Field title ${suffix}`, exact: true }).locator("..").locator("..");
  await titleCard.getByText("Job title lifecycle", { exact: true }).click();
  await titleCard.getByRole("button", { name: "Archive job title" }).click();
  await expect(titleCard.getByText("Archived job title · existing membership retained.")).toBeVisible();
  const lifecycleDetails = titleCard.locator("details").filter({ has: page.getByText("Job title lifecycle", { exact: true }) });
  if ((await lifecycleDetails.getAttribute("open")) === null) await titleCard.getByText("Job title lifecycle", { exact: true }).click();
  await titleCard.getByRole("button", { name: "Reactivate job title" }).click();
  await expect(titleCard.getByRole("button", { name: "Archive job title", exact: true })).toBeVisible();
  await page.goto("/employees/mock-employee-cora");
  await page.getByRole("button", { name: "Default work location", exact: true }).click();
  await page.getByRole("textbox", { name: "Default work location", exact: true }).fill(`Main office ${suffix}`);
  await page.getByRole("form", { name: "Default work location", exact: true }).getByRole("button", { name: "Save changes", exact: true }).click();
  await expect(page.getByText("Default work location saved.")).toBeVisible();
  await page.getByRole("button", { name: "Close", exact: true }).click();
  await page.getByRole("button", { name: "Edit planning coordinate" }).click();
  await page.getByLabel("Latitude", { exact: true }).fill("25.2048");
  await page.getByLabel("Longitude", { exact: true }).fill("55.2708");
  await page.getByRole("button", { name: "Save coordinate", exact: true }).click();
  await expect(page.getByText("Planning coordinate saved.")).toBeVisible();
  await page.getByRole("button", { name: "Close", exact: true }).click();
  await page.getByRole("button", { name: "Clear planning coordinate", exact: true }).click();
  await page.getByRole("form", { name: "Clear employee planning coordinate", exact: true }).getByRole("button", { name: "Clear coordinate", exact: true }).click();
  await expect(page.locator(".workflow-feedback").getByText("Planning coordinate cleared. Assignments remain available in the list.", { exact: true })).toBeVisible();
  await expect(page.getByText("No employee planning coordinate is recorded.", { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await signOut(page);
  for (const person of ["Ava Mercer", "Cora Bell"]) {
    await signIn(page, person);
    await page.goto("/arrangements");
    await expect(page.getByRole("heading", { name: /unavailable|not found/i })).toBeVisible();
    await signOut(page);
  }
});
